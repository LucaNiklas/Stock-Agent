    ("total_assets", "359241", M, 31),  # Total assets
    ("equity", "73733", M, 31),  # Total shareholders' equity
    ("operating_cash_flow", "111482", M, 33),  # Cash generated by operating activities
    ("capex", "12715", M, 33),  # Payments for acquisition of property, plant and equipment
